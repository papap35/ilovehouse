/** 取得某行政區的概略中心點座標，找不到時回傳 null */
export function getDistrictCentroid(city: string, district: string): [number, number] | null {
  return DISTRICT_COORDS[city]?.[district] ?? null;
}

/** 列出目前有座標資料的所有行政區中心點（用於地圖畫圈搜尋等需要遍歷全部行政區的情境） */
export function listAllDistrictCentroids(): DistrictCentroid[] {
  const result: DistrictCentroid[] = [];
  for (const [city, districts] of Object.entries(DISTRICTS_BY_CITY)) {
    for (const district of districts) {
      const coord = DISTRICT_COORDS[city]?.[district];
      if (coord) {
        result.push({ city, district, lat: coord[0], lng: coord[1] });
      }
    }
  }
  return result;
}
